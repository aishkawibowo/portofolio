export function getProject(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

export function getShowcaseProjects(): Project[] {
  return projects.filter((p) => p.hasDetail).sort((a, b) => a.order - b.order);
}

export function getSupportProjects(): Project[] {
  return projects.filter((p) => !p.hasDetail).sort((a, b) => a.order - b.order);
}

export function getFeaturedProjects(): Project[] {
  return projects.filter((p) => p.hasDetail && p.featured).sort((a, b) => a.order - b.order);
}

export function getCategories(): ProjectCategory[] {
  const cats = new Set<ProjectCategory>();
  projects.forEach((p) => p.categories.forEach((c) => cats.add(c)));
  return Array.from(cats);
}